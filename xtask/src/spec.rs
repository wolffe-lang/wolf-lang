#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn extracts_in_order_and_ignores_other_fences() {
        let md =
            "a\n```ebnf\nA ::= 'x'\n```\nprose\n```text\nnot grammar\n```\n```ebnf\nB ::= A\n```\n";
        let got = extract_ebnf(md);
        assert!(got.contains("A ::= 'x'"));
        assert!(got.contains("B ::= A"));
        assert!(!got.contains("not grammar"));
        let a = got.find("A ::=").unwrap();
        let b = got.find("B ::=").unwrap();
        assert!(a < b);
    }

    #[test]
    fn link_check_finds_dangling() {
        let docs = [
            ("02-memory-model.md", "- `[mem.a.1]` rule; see [conc.x.9]."),
            ("03-concurrency.md", "- `[conc.b.2]` rule cites [mem.a.1]."),
        ];
        let errs = link_check(&docs);
        assert_eq!(errs.len(), 1, "{errs:?}");
        assert!(errs[0].contains("conc.x.9"));
    }
}
