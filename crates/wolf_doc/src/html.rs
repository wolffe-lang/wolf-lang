//! Static HTML: readable with JavaScript off, from `file://`, in a
//! terminal browser. There is no script tag anywhere in the output and
//! there never will be — documentation that needs a runtime to be read
//! is documentation that stops working.
//!
//! The markdown subset rendered here is deliberately small and
//! deterministic: paragraphs, fenced code, headings, bullet lists,
//! inline `code`, `**bold**`, `*italic*`, and intra-doc links. Anything
//! else passes through escaped, which is the honest failure mode — a
//! reader sees the source text rather than a mangled page.

use wolf_query::{Directive, DocComment, DocFence, DocModule, DocPackage};

